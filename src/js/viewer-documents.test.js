'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');

let docs;
async function load() {
    if (!docs) docs = await import('./viewer-documents.js');
    return docs;
}

test('a report fills its template, with its styles and script inline', async () => {
    const { reportDocumentHtml } = await load();
    const html = reportDocumentHtml({
        template: '<html><head><title>{{REPORT_TITLE}}</title></head><body>{{REPORT_META}}{{RESULTS}}{{SCREENSHOTS}}</body></html>',
        css: '.r{}',
        js: 'a="$&"',
        title: 'Shop & "co"',
        meta: '<p>meta</p>',
        results: '<div>$\'results</div>',
        screenshots: '<img alt="">',
    });
    assert.equal(html, '<html><head><title>Shop &amp; &quot;co&quot;</title><style>.r{}</style></head><body><p>meta</p><div>$\'results</div><img alt=""><script>a="$&"</script></body></html>');
});

test('a comparison gets one h1, and both style sheets', async () => {
    const { comparisonDocumentHtml, comparisonDescription } = await load();
    const html = comparisonDocumentHtml({
        template: '<html><head><title>{{COMPARISON_TITLE}}</title><meta content="{{COMPARISON_DESCRIPTION}}"></head><body>{{COMPARISON}}</body></html>',
        css: '.a{}',
        comparisonCss: '.b{}',
        js: '',
        title: 'Checkout',
        description: comparisonDescription('2 runs'),
        comparison: '<div class="cmp2"><h2 class="doc-title">Checkout</h2></div>',
    });
    assert.match(html, /<h1 class="doc-title">Checkout<\/h1>/);
    assert.doesNotMatch(html, /<h2 class="doc-title">/);
    assert.match(html, /content="Accessibility comparison of 2 runs, generated by SureA11y\."/);
    assert.match(html, /<style>\.a\{\}\n\.b\{\}<\/style>/);
});

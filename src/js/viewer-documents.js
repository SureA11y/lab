'use strict';

// A report or a comparison as a document of its own: its template filled in,
// with the viewer's styles and script inlined, so it opens anywhere with no
// lab behind it. Pure: the app passes what it has drawn (export.js), the
// command line what it has rendered without a browser (cli/comparison-html.js),
// and both get the same file.

export function escapeAttribute(value) {
    return String(value ?? '')
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;');
}

// Every substitution passes a function, never a string: in a string
// replacement "$&", "$'" and "$`" are patterns, and minified code or a scan
// label can contain them - "$&" alone pastes "</body>" into the script.
function inline(html, { css, js }) {
    return html
        .replace('</head>', () => `<style>${css}</style></head>`)
        .replace('</body>', () => `<script>${js}<\/script></body>`);
}

/**
 * A report (src/report/report-template.html): `meta` and `results` and
 * `screenshots` are HTML as the app draws them.
 */
export function reportDocumentHtml({ template, css, js, title, meta, results, screenshots }) {
    const html = template
        .replaceAll('{{REPORT_TITLE}}', () => escapeAttribute(title))
        .replace('{{REPORT_META}}', () => meta)
        .replace('{{RESULTS}}', () => results)
        .replace('{{SCREENSHOTS}}', () => screenshots);
    return inline(html, { css, js });
}

/**
 * A comparison (src/report/comparison-template.html): `comparison` is the
 * `.cmp2` view as comparisonDiffHTML or comparisonSeriesHTML draw it.
 */
export function comparisonDocumentHtml({ template, css, comparisonCss, js, title, description, comparison }) {
    // The masthead is an h2 in the app, where it sits under the page's own
    // title. A downloaded file is its own document and wants exactly one h1,
    // so the one heading is promoted here rather than printed twice.
    const body = comparison.replace(
        /<h2 class="doc-title">([\s\S]*?)<\/h2>/,
        '<h1 class="doc-title">$1</h1>'
    );
    const html = template
        .replaceAll('{{COMPARISON_TITLE}}', () => escapeAttribute(title))
        .replaceAll('{{COMPARISON_DESCRIPTION}}', () => escapeAttribute(description))
        .replace('{{COMPARISON}}', () => body);
    return inline(html, { css: `${css}\n${comparisonCss}`, js });
}

/** What a comparison's file says it is, from its document (comparison-document.js). */
export function comparisonDescription(summary) {
    const covering = summary ? ` of ${summary}` : '';
    return `Accessibility comparison${covering}, generated by SureA11y.`;
}

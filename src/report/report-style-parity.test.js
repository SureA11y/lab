'use strict';

// The exported report reuses the rendered markup but ships its own stylesheet, so a
// class added to the app stylesheet and not to report.css renders unstyled once
// exported. These are the families the metrics and coverage panels emit.

const { test, describe } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');

const {readAppCss} = require('../css/app-styles');

const APP_CSS = readAppCss();
const REPORT_CSS = fs.readFileSync(path.join(ROOT, 'src', 'report', 'report.css'), 'utf8');

const RENDERER_SOURCES = [
    path.join(ROOT, 'src', 'js', 'a11y-metrics-renderer.js'),
    path.join(ROOT, 'src', 'js', 'a11y-ui.rendering.js'),
    path.join(ROOT, 'src', 'js', 'ui-gauge.js'),
    path.join(ROOT, 'src', 'js', 'run-summary-ui.js'),
    path.join(ROOT, 'src', 'shared', 'issue-dispersion-view.js')
];

// Only the families the export is expected to style; interactive app chrome is
// stripped from the exported markup and deliberately has no report styling.
const EXPORTED_PREFIXES = ['a11y-cov-', 'a11y-review-signals', 'a11y-score-caveat', 'a11y-chip-unevaluated', 'issues-group-coverage', 'issues-group-empty', 'scoreGauge', 'dsp', 'scan-notices', 'a11y-margins', 'node-details-list', 'node-screenshot', 'node-lean', 'node-how-to-check', 'lean-badge', 'instances-lean', 'scan-contexts', 'scan-members', 'scan-filmstrip', 'scan-review-group', 'sr-focusbar', 'scan-summary-list', 'scan-summary-main', 'scan-summary-name', 'scan-summary-meta', 'scan-summary-tags'];

function classesEmittedByRenderers() {
    const found = new Set();
    for (const file of RENDERER_SOURCES) {
        const src = fs.readFileSync(file, 'utf8');
        const literals = [
            ...src.matchAll(/class="([^"$]+)"/g),
            ...src.matchAll(/className\s*=\s*'([^']+)'/g),
            ...src.matchAll(/classList\.add\('([^']+)'\)/g)
        ];
        for (const m of literals) {
            for (const cls of m[1].split(/\s+/).filter(Boolean)) {
                // skip fragments of a concatenated attribute, e.g. "prefix-" + state
                if (/['"+`]/.test(cls) || cls.endsWith('-')) continue;
                if (EXPORTED_PREFIXES.some((p) => cls.startsWith(p))) found.add(cls);
            }
        }
    }
    return [...found].sort();
}

describe('exported report styling parity', () => {
    const classes = classesEmittedByRenderers();
    // A class may exist purely as a hook with no rule anywhere; what must hold is
    // that anything the app styles is styled for the export too.
    const styledInApp = classes.filter((cls) => APP_CSS.includes('.' + cls));

    test('the renderers emit the classes this guard covers', () => {
        assert.ok(classes.length >= 10, `expected several classes, found ${classes.join(', ')}`);
        assert.ok(styledInApp.length >= 10, 'expected most of them to carry app styling');
    });

    test('every class the app styles is styled for the exported report too', () => {
        for (const cls of styledInApp) {
            assert.ok(REPORT_CSS.includes('.' + cls), `${cls} is styled in the app stylesheet but missing from report.css, so it renders unstyled once exported`);
        }
    });

    test('the built report stylesheet is current', () => {
        const built = path.join(ROOT, 'src', 'report', 'report.min.css');
        if (!fs.existsSync(built)) return; // generated by build:report, absent on a clean checkout
        const min = fs.readFileSync(built, 'utf8');
        for (const cls of styledInApp) {
            assert.ok(min.includes(cls), `${cls} is missing from report.min.css, run build:report`);
        }
    });

    test('shared gauge rules are defined identically in both stylesheets', () => {
        const body = (css, sel) => {
            const i = css.indexOf(sel + ' {');
            return i < 0 ? null : css.slice(i, css.indexOf('}', i) + 1).replace(/\s+/g, ' ');
        };
        for (const sel of ['.scoreGauge__unresolved', '.scoreGauge__bottom', '.scoreGauge__readoutMain']) {
            assert.equal(body(REPORT_CSS, sel), body(APP_CSS, sel), `${sel} has drifted between the two stylesheets`);
        }
    });

});

// The exported comparison takes the opposite approach to the report: rather than
// a mirrored stylesheet, build:report extracts the Compare-tab block from the app
// stylesheet, so the two cannot drift. What can break is the extraction itself —
// the markers moving, or a rule landing outside them.
describe('exported comparison styling', () => {
    const COMPARE_START = '/* compare:start';
    const COMPARE_END = '/* compare:end */';

    function comparisonBlock() {
        const start = APP_CSS.indexOf(COMPARE_START);
        const end = APP_CSS.indexOf(COMPARE_END);
        if (start === -1 || end === -1) return null;
        return APP_CSS.slice(APP_CSS.indexOf('*/', start) + 2, end);
    }

    // Both comparison renderers: the pairwise diff and the dashboard the tab
    // shows for three or more reports. Everything either one emits has to reach
    // the extracted block, or it renders unstyled once downloaded.
    const COMPARISON_RENDERERS = [
        path.join(ROOT, 'src', 'js', 'report-comparison-renderer.js'),
        path.join(ROOT, 'src', 'js', 'report-multi-renderer.js'),
    ];

    function classesEmittedByComparisonRenderer() {
        const found = new Set();
        for (const file of COMPARISON_RENDERERS) {
            const src = fs.readFileSync(file, 'utf8');
            for (const m of src.matchAll(/class="([^"$]+)"/g)) {
                for (const cls of m[1].split(/\s+/).filter(Boolean)) {
                    if (/['"+`]/.test(cls) || cls.endsWith('-')) continue;
                    found.add(cls);
                }
            }
        }
        return [...found].sort();
    }

    test('the extraction markers are present and ordered', () => {
        const start = APP_CSS.indexOf(COMPARE_START);
        const end = APP_CSS.indexOf(COMPARE_END);
        assert.notEqual(start, -1, `${COMPARE_START} missing from the app stylesheet — build:report cannot extract the comparison styles`);
        assert.notEqual(end, -1, `${COMPARE_END} missing from the app stylesheet`);
        assert.ok(end > start, 'the compare markers are in the wrong order');
    });

    test('every .cmp2 rule in the app stylesheet sits inside the markers', () => {
        const block = comparisonBlock();
        assert.ok(block, 'compare block not found');
        const inBlock = (block.match(/\.cmp2/g) || []).length;
        const inFile = (APP_CSS.match(/\.cmp2/g) || []).length;
        assert.equal(inFile, inBlock, `${inFile - inBlock} .cmp2 selector(s) live outside the compare markers and would be dropped from the export`);
    });

    test('the comparison renderer only emits classes the block styles', () => {
        const block = comparisonBlock();
        const classes = classesEmittedByComparisonRenderer();
        assert.ok(classes.length >= 10, `expected several classes, found ${classes.join(', ')}`);
        const styledInApp = classes.filter((cls) => APP_CSS.includes('.' + cls));
        for (const cls of styledInApp) {
            assert.ok(
                block.includes('.' + cls) || REPORT_CSS.includes('.' + cls),
                `${cls} is styled in the app stylesheet but reaches neither the extracted compare block nor report.css, so it renders unstyled in an exported comparison`
            );
        }
    });

    test('the built comparison stylesheet is current', () => {
        const built = path.join(ROOT, 'src', 'report', 'comparison.min.css');
        if (!fs.existsSync(built)) return; // generated by build:report, absent on a clean checkout
        const min = fs.readFileSync(built, 'utf8');
        for (const token of ['--side-a', '--side-b', '--shared', '--sev-critical', '--good-line', '--bad-line']) {
            assert.ok(min.includes(token), `${token} is missing from comparison.min.css, run build:report`);
        }
        assert.ok(min.includes('.cmp2'), 'comparison.min.css carries no .cmp2 rules, run build:report');
    });
});

// ---------------------------------------------------------------------------
// The two stylesheets are hand-maintained near-copies: report.css restyles the
// app's components for a standalone document. Most of what differs between them
// is that restyling and is meant to. What these guard is the drift nobody chose
// - a shared rule quietly losing a declaration, a token diverging, a focus
// indicator suppressed in one sheet and not the other - and the step after,
// where the build drops something on its way into the export.
// ---------------------------------------------------------------------------

const csstree = require('css-tree');

function ruleIndex(css) {
    const out = new Map();
    const at = [];
    csstree.walk(csstree.parse(css, { onParseError() {} }), {
        enter(node) {
            if (node.type === 'Atrule') at.push('@' + node.name + ' ' + (node.prelude ? csstree.generate(node.prelude) : ''));
            if (node.type === 'Rule') {
                const key = at.join('|') + '###' + csstree.generate(node.prelude);
                if (!out.has(key)) out.set(key, new Set());
                node.block.children.forEach((d) => {
                    if (d.type === 'Declaration') out.get(key).add(d.property.toLowerCase());
                });
            }
        },
        leave(node) { if (node.type === 'Atrule') at.pop(); }
    });
    return out;
}

function rootTokens(css, selectors) {
    const out = new Map();
    const at = [];
    csstree.walk(csstree.parse(css, { onParseError() {} }), {
        enter(node) {
            if (node.type === 'Atrule') at.push(1);
            if (node.type === 'Rule' && !at.length && selectors.includes(csstree.generate(node.prelude))) {
                node.block.children.forEach((d) => {
                    if (d.type === 'Declaration' && d.property.startsWith('--')) {
                        out.set(d.property, csstree.generate(d.value).trim());
                    }
                });
            }
        },
        leave(node) { if (node.type === 'Atrule') at.pop(); }
    });
    return out;
}

// The report restyles these deliberately: it sets its own display face, and the
// step-builder panel reads on a document rather than in a tool.
const TOKENS_ALLOWED_TO_DIFFER = ['--font-display', '--sb-font', '--sb-muted'];


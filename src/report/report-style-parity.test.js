describe('app and report stylesheet drift', () => {
    const app = ruleIndex(APP_CSS);
    const report = ruleIndex(REPORT_CSS);
    const shared = [...app.keys()].filter((k) => report.has(k));

    test('the two stylesheets still share the rules this guard covers', () => {
        assert.ok(shared.length > 300, `expected the sheets to overlap heavily, found ${shared.length}`);
    });

    test('a token defined in both stylesheets holds the same value', () => {
        const a = rootTokens(APP_CSS, [':root', ':root[data-theme="light"],:root:not([data-theme])']);
        const b = rootTokens(REPORT_CSS, [':root']);
        for (const [name, value] of a) {
            if (!b.has(name) || TOKENS_ALLOWED_TO_DIFFER.includes(name)) continue;
            assert.equal(value, b.get(name),
                `${name} is ${value} in the app stylesheet and ${b.get(name)} in report.css - the exported report would render it differently`);
        }
    });

    test('no shared rule drops a declaration the other sheet sets', () => {
        const drifted = shared.filter((k) => {
            const a = app.get(k), b = report.get(k);
            return [...a].some((p) => !b.has(p)) || [...b].some((p) => !a.has(p));
        });
        for (const key of drifted) {
            assert.ok(KNOWN_PROPERTY_DRIFT.includes(key),
                `${key.split('###')[1]} sets different properties in the two stylesheets and is not in KNOWN_PROPERTY_DRIFT. `
                + 'If the difference is deliberate, add it; if not, the exported report is missing a declaration.');
        }
    });

    test('the known-drift list has no entries that have since converged', () => {
        for (const key of KNOWN_PROPERTY_DRIFT) {
            if (!app.has(key) || !report.has(key)) continue;
            const a = app.get(key), b = report.get(key);
            const differs = [...a].some((p) => !b.has(p)) || [...b].some((p) => !a.has(p));
            assert.ok(differs, `${key.split('###')[1]} no longer drifts - remove it from KNOWN_PROPERTY_DRIFT`);
        }
    });
});

// ---------------------------------------------------------------------------
// The export is minified, and a stylesheet can parse cleanly, render correctly
// in the app and still lose rules on the way through clean-css - which has no
// support for nesting and drops what it cannot read, silently. Everything the
// source declares has to come out the other side.
// ---------------------------------------------------------------------------

// clean-css rewrites some selectors to shorter equivalents.
function normalizeSelector(sel) {
    return sel.replace(/\s+/g, ' ')
        .replace(/["']/g, '')
        .replace(/nth-child\(even\)/g, 'nth-child(2n)')
        .replace(/nth-child\(odd\)/g, 'nth-child(2n+1)')
        .replace(/>\s*\*/g, '>')
        .trim();
}

function shapeOf(css) {
    const selectors = new Set();
    const atRules = new Set();
    csstree.walk(csstree.parse(css, { onParseError() {} }), {
        enter(node) {
            // @font-face is added by the build, not carried from the source.
            if (node.type === 'Atrule' && node.prelude && node.name !== 'font-face') {
                atRules.add('@' + node.name + ' ' + csstree.generate(node.prelude).replace(/\s+/g, ''));
            }
            if (node.type === 'Rule' && node.prelude.children) {
                node.prelude.children.forEach((s) => selectors.add(normalizeSelector(csstree.generate(s))));
            }
        }
    });
    return { selectors, atRules };
}

function assertSurvivesBuild(sourceCss, builtPath, label) {
    if (!fs.existsSync(builtPath)) return; // generated by build:report, absent on a clean checkout
    const src = shapeOf(sourceCss);
    const built = shapeOf(fs.readFileSync(builtPath, 'utf8'));
    for (const at of src.atRules) {
        assert.ok(built.atRules.has(at), `${label}: ${at} is in the source but not the build - clean-css dropped it`);
    }
    for (const sel of src.selectors) {
        assert.ok(built.selectors.has(sel), `${label}: ${sel} is in the source but not the build - clean-css dropped it`);
    }
}

describe('the build carries the stylesheets through intact', () => {
    test('report.css survives minification', () => {
        assertSurvivesBuild(REPORT_CSS, path.join(ROOT, 'src', 'report', 'report.min.css'), 'report.min.css');
    });

    test('the compare block survives extraction and minification', () => {
        const start = APP_CSS.indexOf('/* compare:start');
        const block = APP_CSS.slice(APP_CSS.indexOf('*/', start) + 2, APP_CSS.indexOf('/* compare:end */'));
        assertSurvivesBuild(block, path.join(ROOT, 'src', 'report', 'comparison.min.css'), 'comparison.min.css');
    });
});

// ---------------------------------------------------------------------------
// A rule that clears the outline on :hover outranks the :focus-visible rule it
// shares specificity with whenever it sits later in the file, so a pointer
// resting on a keyboard-focused control takes its focus ring away. Both
// stylesheets have shipped that bug.
// ---------------------------------------------------------------------------

describe('focus indicators survive hover', () => {
    for (const [label, css] of [
        ['the app stylesheet', APP_CSS],
        ['report.css', REPORT_CSS],
        ['ui.css', fs.readFileSync(path.join(ROOT, 'extension', 'ui.css'), 'utf8')]
    ]) {
        test(`${label} has no hover rule that clears the outline`, () => {
            const offenders = [];
            csstree.walk(csstree.parse(css, { positions: true, onParseError() {} }), {
                visit: 'Rule',
                enter(rule) {
                    const sel = csstree.generate(rule.prelude);
                    if (!sel.includes(':hover')) return;
                    rule.block.children.forEach((d) => {
                        if (d.type === 'Declaration' && d.property.toLowerCase() === 'outline'
                            && /^(none|0)$/i.test(csstree.generate(d.value).trim())) {
                            offenders.push(`L${rule.loc.start.line} ${sel}`);
                        }
                    });
                }
            });
            assert.deepEqual(offenders, [], `these hover rules clear the focus outline:\n  ${offenders.join('\n  ')}`);
        });
    }
});
